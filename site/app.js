/* Shared site behaviour. Loaded on every page; each block no-ops when the
   markup it drives isn't present, so there's one file rather than five.

   Everything here degrades: with JS off you get a static page with an open
   nav, no reveal animations, and no scroll-spy — but all content and all
   links still work. */
(() => {
  "use strict";

  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const $ = (sel, scope = document) => scope.querySelector(sel);
  const $$ = (sel, scope = document) => [...scope.querySelectorAll(sel)];

  /* ── sticky header ──────────────────────────────────────────────────────
     A border and blur appear only once the page has scrolled, so the header
     sits flush against the hero at rest. */
  const header = $("[data-header]");
  if (header) {
    const sync = () => header.classList.toggle("is-stuck", window.scrollY > 12);
    sync();
    addEventListener("scroll", sync, { passive: true });
  }

  /* ── mobile navigation ─────────────────────────────────────────────────── */
  const menuBtn = $("[data-menu-btn]");
  const nav = $("[data-nav]");
  if (menuBtn && nav) {
    const setOpen = (open) => {
      nav.classList.toggle("is-open", open);
      menuBtn.setAttribute("aria-expanded", String(open));
      menuBtn.setAttribute("aria-label", open ? "Close navigation" : "Open navigation");
    };

    menuBtn.addEventListener("click", () => setOpen(!nav.classList.contains("is-open")));
    nav.addEventListener("click", (e) => { if (e.target.closest("a")) setOpen(false); });
    addEventListener("keydown", (e) => { if (e.key === "Escape") setOpen(false); });
    // A resize past the breakpoint should not leave the panel stranded open.
    addEventListener("resize", () => { if (innerWidth > 900) setOpen(false); });
  }

  /* ── reveal on scroll ───────────────────────────────────────────────────
     One observer for both the single-element and staggered-group variants.
     Elements are revealed once and then unobserved: re-animating on the way
     back up reads as jitter, not delight. */
  const revealables = $$("[data-reveal], [data-reveal-group]");
  if (revealables.length) {
    if (reduceMotion || !("IntersectionObserver" in window)) {
      revealables.forEach((el) => el.classList.add("is-in"));
    } else {
      const io = new IntersectionObserver(
        (entries) => {
          for (const entry of entries) {
            if (!entry.isIntersecting) continue;
            entry.target.classList.add("is-in");
            io.unobserve(entry.target);
          }
        },
        { rootMargin: "0px 0px -12% 0px", threshold: 0.08 },
      );
      revealables.forEach((el) => io.observe(el));
    }
  }

  /* ── back to top ────────────────────────────────────────────────────────── */
  const toTop = $("[data-totop]");
  if (toTop) {
    const sync = () => toTop.classList.toggle("is-shown", window.scrollY > innerHeight * 0.9);
    sync();
    addEventListener("scroll", sync, { passive: true });
    toTop.addEventListener("click", () => {
      scrollTo({ top: 0, behavior: reduceMotion ? "auto" : "smooth" });
    });
  }

  /* ── reading progress (doc pages) ───────────────────────────────────────── */
  const progress = $("[data-progress]");
  if (progress) {
    const sync = () => {
      const max = document.documentElement.scrollHeight - innerHeight;
      progress.style.width = `${max > 0 ? Math.min(100, (scrollY / max) * 100) : 0}%`;
    };
    sync();
    addEventListener("scroll", sync, { passive: true });
    addEventListener("resize", sync);
  }

  /* ── copy buttons on code blocks ────────────────────────────────────────
     The markup is generated by the docs build; this only wires behaviour, so
     a page with no code blocks costs nothing. */
  $$("[data-copy]").forEach((button) => {
    button.addEventListener("click", async () => {
      const block = button.closest(".bs-code")?.querySelector("code");
      if (!block) return;

      try {
        await navigator.clipboard.writeText(block.innerText);
      } catch {
        // Clipboard API is unavailable over http:// and in some embeddings.
        // Select the text instead so ⌘C still works.
        const range = document.createRange();
        range.selectNodeContents(block);
        const sel = getSelection();
        sel.removeAllRanges();
        sel.addRange(range);
        return;
      }

      const label = button.querySelector("[data-copy-label]");
      const previous = label ? label.textContent : "";
      button.classList.add("is-done");
      if (label) label.textContent = "Copied";
      setTimeout(() => {
        button.classList.remove("is-done");
        if (label) label.textContent = previous;
      }, 1600);
    });
  });

  /* ── table of contents scroll-spy ───────────────────────────────────────
     Tracks the heading nearest the top of the viewport rather than whichever
     one an observer fired for last — with fast scrolling those differ, and
     the naive version highlights the wrong entry. */
  const toc = $("[data-toc]");
  if (toc) {
    const links = $$("a[href^='#']", toc);
    const targets = links
      .map((a) => ({ link: a, el: document.getElementById(decodeURIComponent(a.hash.slice(1))) }))
      .filter((t) => t.el);

    if (targets.length) {
      let ticking = false;
      const sync = () => {
        ticking = false;
        const line = 120;
        let current = targets[0];
        for (const t of targets) {
          if (t.el.getBoundingClientRect().top <= line) current = t;
          else break;
        }
        // At the very bottom the last section may never cross the line.
        if (innerHeight + scrollY >= document.documentElement.scrollHeight - 4) {
          current = targets[targets.length - 1];
        }
        for (const t of targets) t.link.classList.toggle("is-current", t === current);
      };

      addEventListener("scroll", () => {
        if (ticking) return;
        ticking = true;
        requestAnimationFrame(sync);
      }, { passive: true });
      sync();
    }
  }

  /* ── docs index filter ─────────────────────────────────────────────────── */
  const docSearch = $("[data-doc-search]");
  if (docSearch) {
    const cards = $$("[data-doc-card]");
    const groups = $$("[data-doc-group]");
    const empty = $("[data-doc-empty]");

    const apply = () => {
      const q = docSearch.value.trim().toLowerCase();
      let hits = 0;

      for (const card of cards) {
        const match = !q || (card.dataset.docCard || "").includes(q);
        card.classList.toggle("is-hidden", !match);
        if (match) hits++;
      }

      // Hide a group heading whose every card was filtered out.
      for (const group of groups) {
        const visible = $$("[data-doc-card]", group).some((c) => !c.classList.contains("is-hidden"));
        group.classList.toggle("is-hidden", !visible);
      }

      if (empty) empty.classList.toggle("is-shown", hits === 0);
    };

    docSearch.addEventListener("input", apply);
    docSearch.addEventListener("keydown", (e) => {
      if (e.key === "Escape") { docSearch.value = ""; apply(); }
    });

    // "/" focuses search, the way it does in most doc sites.
    addEventListener("keydown", (e) => {
      if (e.key !== "/" || e.metaKey || e.ctrlKey || e.altKey) return;
      const tag = document.activeElement?.tagName;
      if (tag === "INPUT" || tag === "TEXTAREA") return;
      e.preventDefault();
      docSearch.focus();
      docSearch.select();
    });
  }

  /* ── generic tab groups ─────────────────────────────────────────────────
     Used by the learn page's agent-loop stepper. Full keyboard support: the
     arrow keys move between tabs, Home/End jump to the ends. */
  $$("[data-tabs]").forEach((group) => {
    const tabs = $$("[role='tab']", group);
    const panels = tabs.map((t) => document.getElementById(t.getAttribute("aria-controls"))).filter(Boolean);
    if (tabs.length !== panels.length) return;

    const select = (index, focus = true) => {
      tabs.forEach((tab, i) => {
        const on = i === index;
        tab.setAttribute("aria-selected", String(on));
        tab.tabIndex = on ? 0 : -1;
        panels[i].hidden = !on;
      });
      if (focus) tabs[index].focus();
      group.dispatchEvent(new CustomEvent("bs:tab", { detail: { index } }));
    };

    tabs.forEach((tab, i) => {
      tab.addEventListener("click", () => select(i, false));
      tab.addEventListener("keydown", (e) => {
        const keys = { ArrowUp: i - 1, ArrowLeft: i - 1, ArrowDown: i + 1, ArrowRight: i + 1, Home: 0, End: tabs.length - 1 };
        if (!(e.key in keys)) return;
        e.preventDefault();
        select((keys[e.key] + tabs.length) % tabs.length);
      });
    });

    const initial = Math.max(0, tabs.findIndex((t) => t.getAttribute("aria-selected") === "true"));
    select(initial, false);
  });

  /* ── external links ─────────────────────────────────────────────────────
     Anything pointing off-site opens in a new tab with the opener severed.
     Doing it here means no page has to remember the attributes. */
  $$('a[href^="http"]').forEach((a) => {
    if (a.hostname === location.hostname) return;
    a.target = "_blank";
    a.rel = a.rel ? `${a.rel} noopener noreferrer` : "noopener noreferrer";
  });
})();
